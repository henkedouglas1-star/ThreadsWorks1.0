/**
 * Calculates a recommended pillar/phase based on recent history to maintain balanced distribution
 */
export function calculateRecommendedPillar(recentHistory: string[] = []): "attention" | "trust" | "sales" {
  if (!recentHistory || recentHistory.length === 0) {
    return "attention";
  }

  const counts: Record<string, number> = {
    attention: 0,
    trust: 0,
    sales: 0
  };

  const sample = recentHistory.slice(-6);
  sample.forEach(item => {
    const key = (item || "").toLowerCase();
    if (counts[key] !== undefined) {
      counts[key]++;
    }
  });

  const pillars: Array<"attention" | "trust" | "sales"> = ["attention", "trust", "sales"];
  const sorted = pillars.sort((a, b) => (counts[a] || 0) - (counts[b] || 0));
  return sorted[0];
}
